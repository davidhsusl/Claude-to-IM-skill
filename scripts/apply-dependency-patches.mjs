function findMatchingOriginal(content, originals) {
  return originals.find((candidate) => content.includes(candidate));
}

function applyPatches(targetPath) {
  if (!fs.existsSync(targetPath)) {
    return;
  }

  let content = fs.readFileSync(targetPath, 'utf-8');

  for (const patch of patches) {
    if (content.includes(patch.replacement)) {
      console.log(`[postinstall] ${patch.name} already applied in ${path.basename(targetPath)}.`);
      continue;
    }

    const original = findMatchingOriginal(content, patch.originals);
    if (!original) {
      console.warn(`[postinstall] Unable to locate expected block for ${patch.name} in ${path.basename(targetPath)}.`);
      continue;
    }

    content = content.replace(original, patch.replacement);
    console.log(`[postinstall] Applied ${patch.name} in ${path.basename(targetPath)}.`);
  }

  fs.writeFileSync(targetPath, content, 'utf-8');
}

async function rebuildBridgeManagerDist() {
  if (!fs.existsSync(bridgeManagerSourcePath)) {
    return;
  }

  await esbuild.build({
    entryPoints: [bridgeManagerSourcePath],
    bundle: false,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    outfile: bridgeManagerDistPath,
    logLevel: 'silent',
  });

  console.log(`[postinstall] Rebuilt ${path.basename(bridgeManagerDistPath)} from patched source.`);
}

applyPatches(bridgeManagerSourcePath);
await rebuildBridgeManagerDist();